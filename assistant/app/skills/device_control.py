"""Skill: control one or more devices with their hard-coded SmartThings command sets.

Pipeline (each LLM step has its own tiny prompt and a closed-choice schema):
  1. plan            - exact-name fast path (one named device, no "and"/"all"/...), else the LLM
                       splits the request into steps: which devices (enum) + what to do with them
  2. choose actions  - per step, the LLM picks one or more action ids (enum) + values for the
                       device(s). Devices of one step with identical action sets share one call.
  3. validate values - code checks each value against the allowed options / numeric range.
                       Relative changes ("increase by 5%", "a bit dimmer") read the device's
                       current value from /status and become an absolute, clamped value.
  4. execute         - code merges every command for a device into ONE SmartThings POST
                       (devices run concurrently)
  5. confirm         - deterministic template (or LLM phrasing if REPLY_STYLE=llm)
Nothing is executed while any part of the request needs a clarifying question. Every question
and confirmation is generated by code, so the model cannot invent devices or commands.
"""
from __future__ import annotations

import asyncio
import logging
import re
from dataclasses import dataclass, field
from typing import Any

from app.config import Settings
from app.core.context import Device, TurnContext
from app.core.llm import LLM, LLMError
from app.core.skill import REPLY_FORMAT, REPLY_SCHEMA, Skill, SkillResult, register
from app.devices.catalog import CAPABILITY_LABELS, Action, ValueProblem, build_actions, device_line
from app.devices.matching import exact_matches, shortlist
from app.devices.state import READINGS, DeviceState, format_value, read_states, setter_attribute
from app.integrations.smartthings import CommandResult, SmartThingsClient

log = logging.getLogger("agent.skills.device_control")

OK, AMBIGUOUS, NONE, UNCLEAR = "OK", "AMBIGUOUS", "NONE", "UNCLEAR"
SET, INCREASE, DECREASE = "set", "increase", "decrease"

# Words that suggest more than one device or instruction: these skip the exact-name fast path.
MULTI_HINT = re.compile(r"\b(all|every|everything|both|each|and|also|plus|except|other|others|rest)\b|[,&]", re.I)

PLAN_SYSTEM = """Find the devices the user's request is about and what to do with each.

Devices (name: what it can control):
{devices}

Rules:
1. Make one step per instruction. "devices" has the exact names it applies to. "request" says what to do in a few words and keeps every number and detail (e.g. "turn on and dim to 40%").
2. "all", "every", "both" or a plural ("the lights") means every fitting device: put them all in one step.
3. If the user names a room, use only devices in that room.
4. If the user means ONE device but several fit (e.g. "the lamp"), set "result" to "AMBIGUOUS" and put the fitting names in "options".
5. If no device fits, set "result" to "NONE".
6. Otherwise set "result" to "OK".

Reply with JSON only: {{"result": "OK|AMBIGUOUS|NONE", "steps": [{{"devices": ["<exact name>", ...], "request": "<what to do>"}}], "options": ["<exact name>", ...]}}"""

ACTION_SYSTEM = """Map the user's request to the actions of {target}.

Actions (id: what it does | allowed value):
{actions}

Rules:
1. Add one item to "actions" for each thing the user asks for (e.g. "turn on and dim to 40%" is two items).
2. If the action has a value, put it in "value" exactly as listed (or the number). Otherwise "value" is "".
3. "change" is "increase" or "decrease" when the user wants a value changed from where it is now ("by 5%", "a bit brighter", "turn it down"). Then "value" is only the amount ("5%", or "" if no amount). Otherwise "change" is "set".
4. If the user did not say which value they want, set "value" to "".
5. If there is no action for the request, use the action "NONE".
6. If the request is too vague to choose an action, use the action "UNCLEAR".

Reply with JSON only: {{"actions": [{{"action": "<action id>|NONE|UNCLEAR", "change": "set|increase|decrease", "value": "<value or empty>"}}]}}"""

CONFIRM_SYSTEM = """You are {bot}. Device commands were just executed successfully.
Write a short, friendly confirmation (one or two sentences) that mentions every device and what was done. Do not add anything else."""


def _join(names: list[str], word: str = "or") -> str:
    return names[0] if len(names) == 1 else ", ".join(names[:-1]) + f" {word} " + names[-1]


def join_and(names: list[str]) -> str:
    return _join(names, "and")


def _sentence(parts: list[str]) -> str:
    """["turned on A and B", "set C brightness to 40%"] -> "Turned on A and B, and set C brightness to 40%"."""
    text = parts[0] if len(parts) == 1 else ", ".join(parts[:-1]) + ", and " + parts[-1]
    return text[:1].upper() + text[1:]


@dataclass
class Step:
    devices: list[Device]
    request: str


@dataclass
class Pick:
    action: Action
    args: list[Any]
    shown: str  # display value ("" when the action takes none)
    # Relative change: +1 increase / -1 decrease from the device's current value (0 = absolute).
    # args/shown are filled per device once its current value has been read.
    direction: int = 0
    amount: float | None = None  # None = default step
    percent: bool = False        # amount was given in %


@dataclass
class Choice:
    """Outcome of action selection for a group of devices that share one action set."""
    devices: list[Device]
    picks: list[Pick] = field(default_factory=list)
    problem: str = ""        # user-facing text when something could not be done
    blocking: bool = False   # True: ask before executing anything (vague request / missing value)


@dataclass
class Executed:
    device: Device
    picks: list[Pick]
    commands: list[dict[str, Any]]
    result: CommandResult

    def as_dict(self) -> dict[str, Any]:
        return {
            "device_id": self.device.id,
            "device_name": self.device.name,
            "command_generated": {"commands": self.commands},
            "api_result": self.result.as_dict(),
            "status": "success" if self.result.ok else "error",
        }


@register
class DeviceControlSkill(Skill):
    name = "device_control"
    progress_text = "Finding device"
    description = "Change devices: power, brightness, color temperature, shade position, AC temperature/mode/fan, TV volume/input, fan, purifier, lock, vacuum; also relative changes (\"by 5%\", \"a bit brighter\"). Several devices or actions at once are fine."
    examples = ["turn off all the lights", "increase the Desk Lamp brightness by 5%", "turn on Light 1 and dim it to 40%"]
    capability = "control the devices in this building (lights, shades, air conditioners and more), one or many at once"

    def __init__(self, llm: LLM, settings: Settings):
        super().__init__(llm, settings)
        self.st = SmartThingsClient(settings)

    def is_available(self, ctx: TurnContext) -> bool:
        return bool(ctx.devices)

    # ---------- step 1: which devices, what to do with each ----------
    async def plan(self, ctx: TurnContext, request: str) -> list[Step] | SkillResult:
        hits = exact_matches(request, ctx.devices)
        if len(hits) == 1 and not MULTI_HINT.search(request):
            return [Step([hits[0]], request)]

        candidates = shortlist(request, ctx.devices, self.settings.max_device_candidates)
        names = [d.name for d in candidates]
        name_list = {"type": "array", "items": {"type": "string", "enum": names}}
        schema = {
            "type": "object",
            "properties": {
                "result": {"type": "string", "enum": [OK, AMBIGUOUS, NONE]},
                "steps": {
                    "type": "array",
                    "items": {
                        "type": "object",
                        "properties": {"devices": name_list, "request": {"type": "string"}},
                        "required": ["devices", "request"],
                    },
                },
                "options": name_list,
            },
            "required": ["result", "steps", "options"],
        }
        system = PLAN_SYSTEM.format(devices="\n".join(device_line(d) for d in candidates))
        out = await self.llm.complete_json(
            system=system, user=f"Request: {request}", schema=schema, label="device_plan"
        )

        steps: list[Step] = []
        for s in out.get("steps") or []:
            devices = [ctx.device_by_name(n) for n in dict.fromkeys(s.get("devices") or []) if n in names]
            if devices:
                steps.append(Step(devices, (s.get("request") or "").strip() or request))  # type: ignore[arg-type]

        options = list(dict.fromkeys(o for o in out.get("options") or [] if o in names))
        if out["result"] == AMBIGUOUS and len(options) > 1:
            return SkillResult("clarify", f"Which one do you mean: {_join(options)}?", {"options": options})
        if out["result"] == AMBIGUOUS and not steps and options:
            steps = [Step([ctx.device_by_name(options[0])], request)]  # type: ignore[list-item]
        if out["result"] != NONE and steps:
            return steps

        # not a plain command on a named device: let the reasoning skill work out what the person wants
        all_names = [d.name for d in ctx.devices]
        q = f"I couldn't tell which device you mean. For example: {', '.join(all_names[:8])}. Which one would you like to control?"
        return SkillResult("clarify", q, {"options": [], "delegate": "smart_control"})

    # ---------- step 2 + 3: actions and values for a group of identical devices ----------
    async def choose_actions(self, devices: list[Device], request: str) -> Choice:
        names = join_and([d.name for d in devices])
        actions = build_actions(devices[0])  # every device in the group has this same action set
        if not actions:
            verb = "doesn't" if len(devices) == 1 else "don't"
            return Choice(devices, problem=f"{names} {verb} have any controls available in this demo.")
        ids = [a.id for a in actions]
        schema = {
            "type": "object",
            "properties": {
                "actions": {
                    "type": "array",
                    "items": {
                        "type": "object",
                        "properties": {
                            "action": {"type": "string", "enum": ids + [NONE, UNCLEAR]},
                            "change": {"type": "string", "enum": [SET, INCREASE, DECREASE]},
                            "value": {"type": "string"},
                        },
                        "required": ["action", "change", "value"],
                    },
                }
            },
            "required": ["actions"],
        }
        target = (
            f'the device "{devices[0].name}"' if len(devices) == 1
            else "the devices " + ", ".join(f'"{d.name}"' for d in devices) + " (they all have the same actions)"
        )
        system = ACTION_SYSTEM.format(target=target, actions="\n".join(a.describe() for a in actions))
        out = await self.llm.complete_json(
            system=system, user=f"Request: {request}", schema=schema, label="action_select"
        )

        chosen = [x for x in out.get("actions") or [] if x.get("action") in ids]
        has_none = any(x.get("action") == NONE for x in out.get("actions") or [])
        can_do = ", ".join(dict.fromkeys(a.label for a in actions))
        it = "It" if len(devices) == 1 else "They"
        if not chosen and has_none:
            return Choice(devices, problem=f"Sorry, {names} can't do that in this demo. {it} can: {can_do}.")
        if not chosen:
            return Choice(devices, problem=f"What would you like to do with {names}? {it} can: {can_do}.", blocking=True)

        by_id = {a.id: a for a in actions}
        picks: dict[str, Pick] = {}  # one entry per action id; a repeated id keeps the last value
        for x in chosen:
            action = by_id[x["action"]]
            change = x.get("change") or SET
            try:
                if change in (INCREASE, DECREASE):
                    amount, percent = action.change_amount(x.get("value"))
                    picks[action.id] = Pick(action, [], "", 1 if change == INCREASE else -1, amount, percent)
                    continue
                args, shown = action.resolve(x.get("value"))
            except ValueProblem as exc:
                return Choice(devices, problem=f"{names}: {exc}", blocking=True)
            picks[action.id] = Pick(action, args, shown)
        problem = f"{names} can't do everything you asked. {it} can: {can_do}." if has_none else ""
        return Choice(devices, list(picks.values()), problem)

    # ---------- step 3b: relative changes need the device's current value ----------
    def apply_change(self, device: Device, pick: Pick, state: DeviceState | None) -> tuple[list[Pick], str]:
        """Turn a relative pick into absolute picks for one device. Returns (picks, note for the user)."""
        a = pick.action
        attr = setter_attribute(a.capability, a.command)
        noun = READINGS.get((a.capability, attr or ""), CAPABILITY_LABELS.get(a.capability, a.label))
        if state is None or attr is None or (current := state.number(a.capability, attr, a.component)) is None:
            return [], f"I couldn't read the current {noun} of {device.name}, so I left it unchanged."
        args, shown = a.stepped(current, pick.direction, pick.amount, pick.percent)
        if float(shown) == current:
            _, unit = state.value(a.capability, attr, a.component)
            return [], f"{device.name} {noun} is already at {format_value(current, unit)}."
        picks = [Pick(a, args, shown)]
        # The guest page only allows dimming while a light is on: raising brightness turns it on.
        light_off = a.capability == "switchLevel" and state.value("switch", "switch")[0] == "off"
        on = next((x for x in build_actions(device) if x.id == "switch.on"), None)
        if pick.direction > 0 and light_off and on:
            picks.insert(0, Pick(on, [], ""))
        return picks, ""

    async def resolve_changes(self, ctx: TurnContext, choices: list[Choice]) -> tuple[dict[str, tuple[Device, dict[str, Pick]]], list[str]]:
        """Merge every pick per device (absolute values as chosen, relative ones from fresh status)."""
        relative = {d.id: d for c in choices if any(p.direction for p in c.picks) for d in c.devices}
        states: dict[str, DeviceState] = {}
        if relative:
            ctx.progress("device_control.status", "Checking status")
            read = await read_states(self.st, list(relative.values()), ctx.bearer_token, health=False)
            states = {s.device.id: s for s in read}

        per_device: dict[str, tuple[Device, dict[str, Pick]]] = {}
        notes: list[str] = []
        for c in choices:
            for d in c.devices:
                for p in c.picks:
                    resolved = [p]
                    if p.direction:
                        resolved, note = self.apply_change(d, p, states.get(d.id))
                        notes += [note] if note else []
                    for r in resolved:
                        picks = per_device.setdefault(d.id, (d, {}))[1]
                        if r.action.id == "switch.on" and "switch.off" in picks:
                            continue  # the user turned it off on purpose
                        picks[r.action.id] = r
        for d, picks in per_device.values():  # power on goes first in the device's command list
            if "switch.on" in picks:
                ordered = {"switch.on": picks.pop("switch.on"), **picks}
                picks.clear()
                picks.update(ordered)
        return per_device, notes

    # ---------- step 5 ----------
    def summary(self, done: list[Executed]) -> str:
        if len(done) == 1 and len(done[0].picks) == 1:
            p = done[0].picks[0]
            return p.action.confirmation(done[0].device.name, p.shown)
        groups: dict[tuple[str, str], tuple[Pick, list[str]]] = {}  # same action + value -> one phrase
        for ex in done:
            for p in ex.picks:
                groups.setdefault((p.action.id, p.shown), (p, []))[1].append(ex.device.name)
        phrases = [p.action.done_phrase(join_and(devs), p.shown) for p, devs in groups.values()]
        return f"Done! {_sentence(phrases)}."

    async def confirm(self, template: str) -> str:
        if self.settings.reply_style != "llm":
            return template
        try:
            out = await self.llm.complete_json(
                system=CONFIRM_SYSTEM.format(bot=self.settings.bot_name) + "\n\n" + REPLY_FORMAT,
                user=f"What was done: {template}",
                schema=REPLY_SCHEMA,
                label="confirm",
            )
            return out["reply"].strip() or template
        except LLMError:
            return template

    async def run(self, ctx: TurnContext, request: str) -> SkillResult:
        steps = await self.plan(ctx, request)
        if isinstance(steps, SkillResult):
            return steps
        targets = list({d.id: d for s in steps for d in s.devices}.values())
        single = {"device_id": targets[0].id, "device_name": targets[0].name} if len(targets) == 1 else {}

        # Devices of one step that have the same action set share one action_select call.
        jobs: list[tuple[list[Device], str]] = []
        for s in steps:
            groups: dict[tuple[str, ...], list[Device]] = {}
            for d in s.devices:
                groups.setdefault(tuple(a.describe() for a in build_actions(d)), []).append(d)
            jobs += [(g, s.request) for g in groups.values()]

        ctx.progress("device_control.action", "Choosing action" if len(jobs) == 1 else "Choosing actions")
        choices: list[Choice] = await asyncio.gather(*(self.choose_actions(g, r) for g, r in jobs))

        notes = list(dict.fromkeys(c.problem for c in choices if c.problem))
        if any(c.blocking for c in choices) or not any(c.picks for c in choices):
            return SkillResult("clarify", " ".join(notes), {**dict(single), "delegate": "smart_control"})

        # Merge every pick per device so each device gets ONE SmartThings call with all its commands.
        per_device, change_notes = await self.resolve_changes(ctx, choices)
        notes = list(dict.fromkeys(notes + change_notes))
        if not per_device:  # e.g. already at maximum, or the current value couldn't be read
            return SkillResult("clarify", " ".join(notes), dict(single))

        ctx.progress("device_control.send", "Sending command" if len(per_device) == 1 else "Sending commands")

        async def send(device: Device, picks: list[Pick]) -> Executed:
            commands = [p.action.build(p.args) for p in picks]
            return Executed(device, picks, commands, await self.st.execute(device.id, commands, ctx.bearer_token))

        executed: list[Executed] = await asyncio.gather(
            *(send(d, list(picks.values())) for d, picks in per_device.values())
        )
        done = [e for e in executed if e.result.ok]
        failed = [e for e in executed if not e.result.ok]

        data: dict[str, Any] = {"results": [e.as_dict() for e in executed]}
        if len(executed) == 1:  # same top-level fields as the single-device contract
            data.update({k: v for k, v in executed[0].as_dict().items() if k != "status"})

        fail_text = ""
        if failed:
            reasons = ", ".join(dict.fromkeys(e.result.error or "unknown error" for e in failed))
            fail_text = f"I couldn't control {join_and([e.device.name for e in failed])} right now ({reasons})."
        if not done:
            return SkillResult("error", f"Sorry, {fail_text} Please try again.", data)

        message = await self.confirm(self.summary(done))
        extra = ([f"But {fail_text}"] if fail_text else []) + notes
        return SkillResult("success", " ".join([message] + extra), data)
